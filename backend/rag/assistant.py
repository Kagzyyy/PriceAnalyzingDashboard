"""
Groq-powered RAG research assistant (free tier, Llama 3.3 70B).
"""
import logging
from datetime import date
from groq import Groq
from backend.config import GROQ_API_KEY
from backend.rag.embeddings import search

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """You are an expert NSE (National Stock Exchange of India) market analyst assistant.

You have access to today's AI-generated stock predictions, technical analysis, and sector data for NSE-listed stocks.
The predictions are generated by an XGBoost model trained on technical indicators.

Guidelines:
- Answer ONLY based on the context provided. Do not make up stock prices or predictions.
- Always mention sector context when discussing stocks.
- When listing stocks, include their prediction confidence and direction.
- Be direct and concise — traders need quick, actionable answers.
- Mention risk caveats when appropriate (predictions are probabilistic, not guarantees).
- Today's date is {today}.

If the context doesn't contain enough information to answer, say so clearly."""


def query(user_question: str, top_k: int = 12) -> dict:
    """
    Answer a market research question using RAG.
    Returns {answer, sources, query}
    """
    if not GROQ_API_KEY:
        return {
            "answer": "Please set your GROQ_API_KEY in the .env file to use the research assistant.",
            "sources": [],
            "query": user_question,
        }

    docs = search(user_question, top_k=top_k)

    if not docs:
        return {
            "answer": "No market data available yet. Please run a data refresh first.",
            "sources": [],
            "query": user_question,
        }

    context = "\n\n".join(f"[{i}] {doc['text']}" for i, doc in enumerate(docs, 1))
    today = str(date.today())
    system = SYSTEM_PROMPT.format(today=today)

    prompt = f"""Market data context:
{context}

User question: {user_question}

Please answer based on the above context."""

    client = Groq(api_key=GROQ_API_KEY)
    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": prompt},
        ],
        max_tokens=1024,
    )
    answer = response.choices[0].message.content

    sources = []
    for doc in docs[:5]:
        meta = doc.get("metadata", {})
        if meta.get("type") == "stock":
            sources.append({
                "type": "stock",
                "symbol": meta.get("symbol"),
                "name": meta.get("name"),
                "sector": meta.get("sector"),
                "direction": meta.get("direction"),
                "confidence": meta.get("confidence"),
            })
        elif meta.get("type") == "sector":
            sources.append({
                "type": "sector",
                "sector": meta.get("sector"),
                "bullish_pct": meta.get("bullish_pct"),
            })
        elif meta.get("type") == "market_overview":
            sources.append({
                "type": "market_overview",
                "sentiment": meta.get("sentiment"),
                "longs": meta.get("longs"),
                "shorts": meta.get("shorts"),
            })

    return {"answer": answer, "sources": sources, "query": user_question}


